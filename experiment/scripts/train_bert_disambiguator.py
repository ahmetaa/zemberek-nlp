#!/usr/bin/env python3
"""
Fine-tunes a Turkish Transformer model (e.g., dbmdz/bert-base-turkish-cased)
for morphological ambiguity resolution using the annotated JSONL dataset
generated by llm_disambiguator.py.

Usage:
  python3 train_bert_disambiguator.py \
    --train path/to/annotated_train.jsonl \
    --dev path/to/annotated_dev.jsonl \
    --model-name dbmdz/bert-base-turkish-cased \
    --output-dir models/bert-turkish-disambiguator \
    --epochs 3 \
    --batch-size 16 \
    --lr 2e-5 \
    --export-onnx models/bert_disambiguator.onnx
"""

import argparse
import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("TrainBertDisambiguator")


def check_dependencies():
    missing = []
    for pkg in ["torch", "transformers"]:
        try:
            __import__(pkg)
        except ImportError:
            missing.append(pkg)
    if missing:
        logger.error("Missing required dependencies: %s", ", ".join(missing))
        logger.error("Please install them with: pip install torch transformers accelerate datasets")
        return False
    return True


class DisambiguationExample:
    """Represents an ambiguous token decision in context."""
    def __init__(self, sentence: str, word_index: int, surface: str, candidates: List[str], target_id: int):
        self.sentence = sentence
        self.word_index = word_index
        self.surface = surface
        self.candidates = candidates
        self.target_id = target_id


def load_dataset(jsonl_path: Path) -> List[DisambiguationExample]:
    examples = []
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                data = json.loads(line)
            except json.JSONDecodeError:
                continue

            text = data.get("text", "")
            tokens = data.get("tokens", [])
            for token in tokens:
                if not token.get("is_ambiguous", False):
                    continue
                selected_id = token.get("selected_candidate_id")
                if selected_id is None:
                    continue

                candidates = token.get("candidates", [])
                if len(candidates) < 2:
                    continue

                cand_texts = [
                    f"{c.get('surface', token.get('surface', ''))} -> {c.get('lemma', '')}:{c.get('pos', '')} {c.get('oflazer_style', '')}"
                    for c in candidates
                ]

                examples.append(
                    DisambiguationExample(
                        sentence=text,
                        word_index=token.get("index", 0),
                        surface=token.get("surface", ""),
                        candidates=cand_texts,
                        target_id=int(selected_id),
                    )
                )

    logger.info("Loaded %d ambiguous training examples from %s", len(examples), jsonl_path)
    return examples


def train_model(args):
    import torch
    import torch.nn as nn
    from torch.utils.data import DataLoader, Dataset
    from transformers import AutoModel, AutoTokenizer, get_linear_schedule_with_warmup

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    logger.info("Using device: %s", device)

    logger.info("Loading pretrained tokenizer and model: %s", args.model_name)
    tokenizer = AutoTokenizer.from_pretrained(args.model_name)
    backbone = AutoModel.from_pretrained(args.model_name)

    # Scorer head: scores candidate analysis in sentence context
    class BertDisambiguator(nn.Module):
        def __init__(self, encoder, hidden_size: int = 768):
            super().__init__()
            self.encoder = encoder
            self.classifier = nn.Sequential(
                nn.Linear(hidden_size * 2, hidden_size),
                nn.ReLU(),
                nn.Dropout(0.1),
                nn.Linear(hidden_size, 1),
            )

        def forward(self, input_ids, attention_mask, token_type_ids=None):
            outputs = self.encoder(
                input_ids=input_ids,
                attention_mask=attention_mask,
                token_type_ids=token_type_ids,
            )
            # Use pooler output or mean pooling
            cls_repr = outputs.last_hidden_state[:, 0, :]
            # Candidate representation from mean pooling of candidate segment
            cand_repr = outputs.last_hidden_state[:, -1, :]
            combined = torch.cat([cls_repr, cand_repr], dim=-1)
            score = self.classifier(combined).squeeze(-1)
            return score

    model = BertDisambiguator(backbone, hidden_size=backbone.config.hidden_size).to(device)

    train_examples = load_dataset(Path(args.train))
    if not train_examples:
        logger.error("No valid ambiguous examples found in %s", args.train)
        return

    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.01)
    total_steps = len(train_examples) * args.epochs // args.batch_size
    scheduler = get_linear_schedule_with_warmup(
        optimizer, num_warmup_steps=int(total_steps * 0.1), num_training_steps=total_steps
    )

    loss_fn = nn.CrossEntropyLoss()

    logger.info("Starting training for %d epochs...", args.epochs)
    model.train()
    for epoch in range(args.epochs):
        epoch_loss = 0.0
        correct = 0
        total = 0

        for ex in train_examples:
            # Pair sentence with each candidate: [CLS] sentence [SEP] candidate_i [SEP]
            pairs = [(ex.sentence, cand) for cand in ex.candidates]
            encoded = tokenizer(
                [p[0] for p in pairs],
                [p[1] for p in pairs],
                padding=True,
                truncation=True,
                max_length=args.max_length,
                return_tensors="pt",
            ).to(device)

            scores = model(
                input_ids=encoded["input_ids"],
                attention_mask=encoded["attention_mask"],
                token_type_ids=encoded.get("token_type_ids"),
            )

            # Target is candidate index (cross-entropy over candidates)
            target = torch.tensor([ex.target_id], device=device)
            loss = loss_fn(scores.unsqueeze(0), target)

            optimizer.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            scheduler.step()

            epoch_loss += loss.item()
            pred = torch.argmax(scores).item()
            if pred == ex.target_id:
                correct += 1
            total += 1

        accuracy = correct / max(total, 1)
        logger.info(
            "Epoch %d/%d - Loss: %.4f - Accuracy: %.4f (%d/%d)",
            epoch + 1, args.epochs, epoch_loss / max(total, 1), accuracy, correct, total
        )

    # Save fine-tuned model and tokenizer
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tokenizer.save_pretrained(out_dir)
    torch.save(model.state_dict(), out_dir / "bert_disambiguator.pt")
    logger.info("Saved fine-tuned model and tokenizer to %s", out_dir)

    # Export ONNX if requested
    if args.export_onnx:
        onnx_path = Path(args.export_onnx)
        onnx_path.parent.mkdir(parents=True, exist_ok=True)
        try:
            logger.info("Exporting model to ONNX: %s", onnx_path)
            dummy_input = tokenizer(
                ["Eve geldim."], ["ev -> ev:Noun ev+Noun+A3sg+Dat"],
                return_tensors="pt"
            ).to(device)
            torch.onnx.export(
                model,
                (dummy_input["input_ids"], dummy_input["attention_mask"]),
                onnx_path,
                input_names=["input_ids", "attention_mask"],
                output_names=["score"],
                dynamic_axes={
                    "input_ids": {0: "batch_size", 1: "seq_len"},
                    "attention_mask": {0: "batch_size", 1: "seq_len"},
                    "score": {0: "batch_size"},
                },
                opset_version=14,
            )
            logger.info("ONNX export completed: %s", onnx_path)
        except Exception as e:
            logger.warning("ONNX export failed: %s", e)


def main():
    parser = argparse.ArgumentParser(description="Train BERT morphological disambiguator for Turkish")
    parser.add_argument("--train", "-t", required=True, help="Path to training annotated JSONL file")
    parser.add_argument("--dev", "-d", help="Path to development annotated JSONL file")
    parser.add_argument("--model-name", "-m", default="dbmdz/bert-base-turkish-cased", help="Hugging Face model name")
    parser.add_argument("--output-dir", "-o", default="models/bert_disambiguator", help="Directory to save model")
    parser.add_argument("--epochs", "-e", type=int, default=3, help="Number of training epochs")
    parser.add_argument("--batch-size", "-b", type=int, default=16, help="Batch size")
    parser.add_argument("--lr", type=float, default=2e-5, help="Learning rate")
    parser.add_argument("--max-length", type=int, default=128, help="Maximum sequence length")
    parser.add_argument("--export-onnx", help="Export path for ONNX format model")

    args = parser.parse_args()

    if not check_dependencies():
        sys.exit(1)

    train_model(args)


if __name__ == "__main__":
    main()

